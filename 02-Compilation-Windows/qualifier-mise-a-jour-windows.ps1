# StorageScope v5.89 - two-version upgrade qualification; disposable Windows VM ONLY.
# Auteur: Abdelhalim Talbi. No automatic cleanup of installed files or user data.
param([Parameter(Mandatory=$true)][string]$PreviousInstaller,
      [Parameter(Mandatory=$true)][string]$NewInstaller,
      [string]$ReportPath = (Join-Path $PSScriptRoot 'build-logs/upgrade-e2e-v5.89.json'))
$ErrorActionPreference = 'Stop'
$install = Join-Path $env:LOCALAPPDATA 'Programs\StorageScope'
$data = Join-Path $env:LOCALAPPDATA 'StorageScope'
$backup = Join-Path $env:LOCALAPPDATA 'StorageScope-Upgrade-Backups'
if ((Test-Path $install) -or (Test-Path $data) -or (Test-Path $backup)) { throw 'VM vierge requise: donnees, sauvegardes ou installation existantes.' }
foreach ($file in @($PreviousInstaller,$NewInstaller)) {
    if (-not (Test-Path -LiteralPath $file -PathType Leaf)) { throw "Installateur absent: $file" }
}
if ([IO.Path]::GetFullPath($PreviousInstaller) -eq [IO.Path]::GetFullPath($NewInstaller)) { throw 'Deux installateurs distincts requis' }
$reportDir = Split-Path -Parent $ReportPath
New-Item -ItemType Directory -Force -Path $reportDir | Out-Null
$oldLog = Join-Path $reportDir 'upgrade-previous-v5.89.log'
$newLog = Join-Path $reportDir 'upgrade-new-v5.89.log'
$report = [ordered]@{ version='5.89'; scenario='two-installer-upgrade'; passed=$false; previous_exit=$null; new_exit=$null; backup_verified=$false; source_preserved=$false; logs_present=$false; error=$null }
function Invoke-Installer([string]$File,[string]$Log) {
    $args = @('/VERYSILENT','/SUPPRESSMSGBOXES','/NORESTART','/SP-',('/LOG="{0}"' -f $Log))
    $proc = Start-Process -FilePath $File -ArgumentList $args -PassThru -Wait
    return $proc.ExitCode
}
try {
    $report.previous_exit = Invoke-Installer $PreviousInstaller $oldLog
    if ($report.previous_exit -ne 0) { throw "Ancien installateur: code $($report.previous_exit)" }
    $exe = Join-Path $install 'StorageScope.exe'
    if (-not (Test-Path -LiteralPath $exe -PathType Leaf)) { throw 'Ancien EXE absent' }
    & $exe --self-test
    if ($LASTEXITCODE -ne 0) { throw 'Ancien EXE: self-test KO' }
    New-Item -ItemType Directory -Force -Path $data | Out-Null
    $sentinel = Join-Path $data 'upgrade-preservation-v589.txt'
    $views = Join-Path $data 'governance-views.json'
    Set-Content -LiteralPath $sentinel -Value 'PRESERVE-V589' -Encoding ASCII
    [IO.File]::WriteAllText($views, '{}', [Text.UTF8Encoding]::new($false))
    $beforeSentinel = (Get-FileHash -LiteralPath $sentinel -Algorithm SHA256).Hash
    $beforeViews = (Get-FileHash -LiteralPath $views -Algorithm SHA256).Hash
    # The new installer invokes its EMBEDDED frozen upgrade gate automatically.
    # No Python interpreter is required on the target VM.
    $report.new_exit = Invoke-Installer $NewInstaller $newLog
    if ($report.new_exit -ne 0) { throw "Nouvel installateur: code $($report.new_exit)" }
    & $exe --self-test
    if ($LASTEXITCODE -ne 0) { throw 'Nouvel EXE: self-test KO' }
    $report.source_preserved = ((Get-FileHash -LiteralPath $sentinel -Algorithm SHA256).Hash -eq $beforeSentinel) -and ((Get-FileHash -LiteralPath $views -Algorithm SHA256).Hash -eq $beforeViews)
    if (-not $report.source_preserved) { throw 'Fichiers utilisateur modifies' }
    # Gate snapshot inventory is a JSON manifest generated by backup_snapshot.
    $manifests = @(Get-ChildItem -LiteralPath $backup -Filter manifest.json -Recurse -File -ErrorAction SilentlyContinue)
    $report.backup_verified = $false
    foreach ($manifest in $manifests) {
        $obj = Get-Content -LiteralPath $manifest.FullName -Raw | ConvertFrom-Json
        $copy = Join-Path $manifest.DirectoryName 'governance-views.json'
        if (Test-Path -LiteralPath $copy -PathType Leaf) {
            if ((Get-FileHash -LiteralPath $copy -Algorithm SHA256).Hash -eq $beforeViews) { $report.backup_verified = $true; break }
        }
    }
    if (-not $report.backup_verified) { throw 'Aucune sauvegarde des vues conforme aux donnees source' }
    $report.logs_present = (Test-Path -LiteralPath $oldLog -PathType Leaf) -and (Test-Path -LiteralPath $newLog -PathType Leaf)
    if (-not $report.logs_present) { throw 'Journaux installateur absents' }
    $report.passed = $true
    Write-Host 'PASS: upgrade, sauvegarde, empreintes, journaux et self-tests.'
} catch {
    $report.error = $_.Exception.Message
    throw
} finally {
    $report | ConvertTo-Json -Depth 5 | Set-Content -LiteralPath $ReportPath -Encoding UTF8
    Write-Warning 'Ne pas nettoyer automatiquement la VM: conserver les preuves de qualification.'
}
